// دکمه‌ی Back گوشی اندروید (و سوایپ لبه) باید رفتار منطقی داشته باشه: اگه یک
// پنجره/پنل باز باشه، فقط همون بسته بشه، نه کل اپ. چون پنجره‌ها/مودال‌ها توی
// کامپوننت‌های مختلف (ProductTab، MaterialTab، GalleryTab، خودِ App.jsx و...)
// با state محلی مدیریت می‌شن، به‌جای اینکه App.jsx مستقیم به همه‌ی این
// state ها دسترسی داشته باشه، از یک stack سراسری ساده استفاده می‌کنیم:
// هر کامپوننتی که یک مودال/پنل باز می‌کنه، تا وقتی بازه یک تابع «بستن» ثبت
// می‌کنه؛ با فشردن Back فقط آخرین (بالاترین/جدیدترین) مودال بسته می‌شه.
// اگه هیچ مودالی ثبت‌شده‌ای باز نباشه، App.jsx خودش تصمیم می‌گیره (تب پیش‌فرض
// یا خروج از اپ).
// ------------------------------------------------------------

const stack = [];

export function pushBackHandler(fn) {
  stack.push(fn);
  return () => {
    const idx = stack.indexOf(fn);
    if (idx !== -1) stack.splice(idx, 1);
  };
}

// اگه مودال بازی ثبت‌شده باشه صداش می‌زنه (که خودش رو ببنده) و true برمی‌گردونه.
// اگه چیزی برای بستن نبود، false برمی‌گردونه تا App.jsx منطق بعدی (تب/خروج) رو اجرا کنه.
export function consumeBack() {
  if (stack.length === 0) return false;
  const top = stack[stack.length - 1];
  top();
  return true;
}
